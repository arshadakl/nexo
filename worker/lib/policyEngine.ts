import { logger } from './logger';

export interface ReplyPolicyResult {
  allowed: boolean;
  reason?: string;
  flag?: string;
}

export interface ReplyPolicyOptions {
  /**
   * Figures a reviewer already sent to this customer in this conversation. An automatic reply may
   * repeat them for this customer only; they never become a general price.
   */
  approvedFigures?: string[];
}

/**
 * Currency & Price pattern detector.
 * Detects AED, INR, USD, EUR, GBP, dirhams, rupees, and digit combinations
 * to prevent accidental price quotation before authorized packages are enabled.
 */
const PRICE_REGEX = /\b(AED|INR|USD|EUR|GBP|dirhams?|rupees?|\$|₹)\s*\d+([.,]\d+)?\b|\b\d+([.,]\d+)?\s*(AED|INR|USD|dirhams?|rupees?)\b/i;
const PRICE_REGEX_GLOBAL = new RegExp(PRICE_REGEX.source, 'gi');

function figureOf(match: string): string {
  return match.replace(/[^\d.]/g, '').replace(/\.0+$/, '');
}

/** Extracts the numeric amounts of every price mention in a text. */
export function extractPriceFigures(text: string | null | undefined): string[] {
  if (!text) return [];
  return Array.from(text.matchAll(PRICE_REGEX_GLOBAL), (m) => figureOf(m[0]));
}

/**
 * Worker-side authoritative policy engine.
 * Inspects outbound text generated by the model before any Meta API call.
 */
export function evaluateReplyPolicy(
  replyText: string | null | undefined,
  options: ReplyPolicyOptions = {}
): ReplyPolicyResult {
  if (!replyText || typeof replyText !== 'string' || replyText.trim() === '') {
    return {
      allowed: false,
      reason: 'Empty or invalid reply text',
      flag: 'EMPTY_REPLY',
    };
  }

  // Check for unauthorized pricing quotation
  if (PRICE_REGEX.test(replyText)) {
    const approved = new Set(options.approvedFigures || []);
    const figures = extractPriceFigures(replyText);
    if (approved.size > 0 && figures.length > 0 && figures.every((f) => approved.has(f))) {
      return { allowed: true };
    }
    logger.warn('Policy violation: Outbound reply contains unauthorized price quotation', {
      snippet: replyText.slice(0, 150),
    });
    return {
      allowed: false,
      reason: 'Outbound message attempted unauthorized price quotation',
      flag: 'UNAUTHORIZED_PRICE_QUOTATION',
    };
  }

  return { allowed: true };
}
